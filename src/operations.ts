/**
 * Every merchant API operation, keyed by its OpenAPI operationId. Resource methods call the client
 * with one of these entries, and test/spec-conformance.spec.ts checks the table against
 * spec/public.v1.yaml: method, path, whether `Idempotency-Key` is accepted or required, the
 * query parameters, list-ness and test-mode-only flags. `sdk` names the method that implements it.
 */
import type { OperationId } from './types';

export type HttpMethod = 'GET' | 'POST' | 'PATCH' | 'DELETE';
/** none: the header is never sent · optional: sent (generated when omitted) · required: same, and the API insists. */
export type Idempotency = 'none' | 'optional' | 'required';

export interface OperationDef<Op extends OperationId = OperationId> {
  readonly id: Op;
  readonly method: HttpMethod;
  /** Path under /api/v1, with {param} placeholders. */
  readonly path: string;
  readonly idempotency: Idempotency;
  /** The SDK method (`resource.method`) that implements the operation. */
  readonly sdk: string;
  /** Accepted query parameters (bracket suffixes removed). */
  readonly query?: readonly string[];
  /** The response `data` is an array with `meta`. */
  readonly list?: true;
  /** Non-JSON response. */
  readonly accept?: 'text/csv';
  /** Only callable with a test key; the SDK refuses it locally with a live key. */
  readonly testModeOnly?: true;
}

